"""Regenerates the colour-contrast section of src/styles/globals.css (run: python scripts/gen_theme.py).

Theme rule: text never uses pure black or pure white. Every surface sets CSS variables for its text colours, so any
element uses the colours of its NEAREST surface (nesting just works):
  light surfaces (page, white / pale cards)  navy #14213D, muted #475569, darker accent colours
  dark surfaces (navy / slate-700..950)      soft light #EAF0FF, muted #A8B5D1, lighter accent colours
  saturated buttons (blue, red, green ...)   soft light #F5F8FF
  bright yellow / amber surfaces             navy
"""
import os
import re

p = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'styles', 'globals.css')
s = open(p, encoding='utf8').read()
cut = s.index('/* Global Light Theme Overrides') if '/* Global Light Theme Overrides' in s else s.index('/* ----------------------------------------------------------------------------------------------\n   Contrast theme')
head = s[:cut]

ALPHAS = ['', '/40', '/50', '/60', '/70', '/80', '/85', '/90', '/95']
DARK_TOKENS = []
for shade in ('700', '800', '900', '950'):
    for color in ('slate', 'gray', 'zinc', 'neutral'):
        for a in ALPHAS:
            DARK_TOKENS.append(f'bg-{color}-{shade}{a}')
for hexv in ('000B1C', '000d21', '0A122C', '081329', '0f203c', '040810', '0b0f19', '081229', '0F172A', '020617', '050A18'):
    DARK_TOKENS.append(f'bg-[#{hexv}]')
DARK_TOKENS += ['bg-black', 'bg-black/60', 'bg-black/70', 'bg-black/80']
DARK_CLASSES = ['high-contrast-dark-card']

SAT_TOKENS = []
for color, shades in (('blue', ('500', '600', '700', '800')), ('cyan', ('600', '700')), ('purple', ('500', '600', '700')), ('indigo', ('500', '600', '700')),
                      ('emerald', ('500', '550', '600', '700')), ('green', ('600', '700')), ('red', ('500', '600', '650', '700')), ('rose', ('600',)),
                      ('orange', ('600',)), ('teal', ('600', '700')), ('pink', ('600',))):
    for sh in shades:
        SAT_TOKENS.append(f'bg-{color}-{sh}')
BRIGHT_TOKENS = ['bg-amber-300', 'bg-amber-400', 'bg-amber-500', 'bg-yellow-300', 'bg-yellow-400', 'bg-yellow-500', 'bg-orange-400', 'bg-orange-500',
                 'bg-[#FBBF24]', 'bg-[#F59E0B]', 'bg-[#FCD34D]']
LIGHT_TOKENS = ['bg-white', 'bg-white/80', 'bg-white/90', 'bg-slate-50', 'bg-slate-100', 'bg-slate-200', 'bg-slate-100/40', 'glass-card', 'high-contrast-light-card']

NEUTRAL_STRONG = ['text-white', 'text-slate-50', 'text-slate-100', 'text-slate-200', 'text-slate-300', 'text-gray-100', 'text-gray-200', 'text-gray-300', 'text-blue-100', 'text-cyan-100', 'text-indigo-100', 'text-[#000B1C]']
NEUTRAL_MUTED = ['text-slate-350', 'text-slate-400', 'text-slate-450', 'text-slate-500', 'text-slate-600', 'text-gray-400', 'text-gray-500', 'text-gray-600']
ACCENTS = {  # family: (colour on light surfaces, colour on dark surfaces)
    'blue': ('#1D4ED8', '#7DB2FF'), 'cyan': ('#155E75', '#5CD6EC'), 'sky': ('#0369A1', '#7DD3FC'),
    'emerald': ('#065F46', '#4ADE9C'), 'green': ('#166534', '#4ADE80'), 'teal': ('#0F766E', '#5EEAD4'),
    'amber': ('#92400E', '#FCD34D'), 'yellow': ('#A16207', '#FDE047'), 'orange': ('#C2410C', '#FDBA74'),
    'red': ('#B91C1C', '#FCA5A5'), 'rose': ('#BE123C', '#FDA4AF'), 'pink': ('#BE185D', '#F9A8D4'),
    'purple': ('#6D28D9', '#C4B5FD'), 'indigo': ('#4338CA', '#A5B4FC'), 'violet': ('#6D28D9', '#C4B5FD'),
}


def esc(tok):
    return re.sub(r'([/\[\]#])', r'\\\1', tok)


def sel(tokens, classes=()):
    return [f'.{esc(t)}' for t in tokens] + [f'.{c}' for c in classes]


def join(lst):
    return ',\n'.join(lst)


def var_block(strong, muted, idx, on_sat=False):
    v = [f'--t-strong: {strong};', f'--t-muted: {muted};']
    for fam, cols in ACCENTS.items():
        v.append(f'--a-{fam}: {strong if on_sat else cols[idx]};')
    return ' '.join(v)


def util_rules():
    r = [join([f'.{esc(t)}' for t in NEUTRAL_STRONG]) + ' { color: var(--t-strong) !important; }',
         join([f'.{t}' for t in NEUTRAL_MUTED]) + ' { color: var(--t-muted) !important; }']
    for fam in ACCENTS:
        toks = [f'.text-{fam}-{sh}' for sh in ('300', '400', '450', '500', '550', '600', '650', '700')]
        if fam == 'amber': toks += ['.text-\[\#FBBF24\]', '.text-\[\#F59E0B\]', '.text-\[\#FCD34D\]']
        r.append(join(toks) + f' {{ color: var(--a-{fam}) !important; }}')
    return '\n'.join(r)


out = []
out.append('/* ----------------------------------------------------------------------------------------------\n'
           '   Contrast theme. No text is pure black or pure white. Every surface sets CSS variables for its text colours,\n'
           '   so an element uses the colours of its NEAREST surface (nesting just works).\n'
           '     light surfaces: navy #14213D / muted #475569     dark surfaces: #EAF0FF / muted #A8B5D1\n'
           '   Generated by gen_theme.py\n'
           '   ---------------------------------------------------------------------------------------------- */\n'
           ':root, body { ' + var_block('#14213D', '#475569', 0) + ' color: #14213D; }\n'
           'body {\n  background: linear-gradient(135deg, #FCD34D 0%, #FFFFFF 100%) fixed !important;\n  color: #14213D !important;\n}\n'
           'h1, h2, h3, h4, h5, h6, p, span, li, label, th, td, small, strong, b, em, dt, dd, summary, legend, a, button { color: inherit; }\n')
out.append('/* light surfaces */\n' + join(sel(LIGHT_TOKENS)) + ' { ' + var_block('#14213D', '#475569', 0) + ' color: #14213D; }')
out.append('/* dark surfaces */\n' + join(sel(DARK_TOKENS, DARK_CLASSES)) + ' { ' + var_block('#EAF0FF', '#A8B5D1', 1) + ' color: #EAF0FF; }')
out.append('/* saturated buttons and badges */\n' + join(sel(SAT_TOKENS)) + ' { ' + var_block('#F5F8FF', '#DCE6FF', 1, True) + ' color: #F5F8FF; }')
out.append('/* bright yellow surfaces */\n' + join(sel(BRIGHT_TOKENS)) + ' { ' + var_block('#14213D', '#475569', 0) + ' color: #14213D; }')
out.append('/* utility colours resolve through the variables of the nearest surface */')
out.append(util_rules())

SAT_BG = {'blue': '#2563EB', 'cyan': '#0E7490', 'purple': '#7C3AED', 'indigo': '#4F46E5', 'emerald': '#047857', 'green': '#15803D', 'red': '#B91C1C',
          'rose': '#BE123C', 'orange': '#C2410C', 'teal': '#0F766E', 'pink': '#BE185D'}
bg_rules = []
for t in SAT_TOKENS:
    fam = t.split('-')[1]
    col = SAT_BG[fam]
    if t.endswith('700') or t.endswith('800'):
        col = {'blue': '#1D4ED8', 'indigo': '#4338CA', 'purple': '#6D28D9'}.get(fam, col)
    bg_rules.append(f'.{esc(t)} {{ background-color: {col} !important; }}')
    bg_rules.append(f'.{esc("hover:" + t)}:hover {{ background-color: {col} !important; filter: brightness(0.92); }}')
out.append('/* saturated backgrounds: dark enough for light text (AA contrast) */' + chr(10) + chr(10).join(bg_rules))
# semi-transparent dark panels over the light page look muddy grey: make them solid dark
alpha_dark = [t for t in DARK_TOKENS if '/' in t and t.startswith('bg-') and not t.startswith('bg-black')]
out.append('/* translucent dark panels become solid dark panels */' + chr(10) + join(sel(alpha_dark)) + ' { background-color: rgba(21, 30, 53, 0.96) !important; }')

# Buttons and button-like links never use a black / dark fill: a dark token on a <button> or <a> becomes a light slate button
DARK_BTN = ', '.join(f'button{t}, a{t}, [role="button"]{t}' for t in sel(DARK_TOKENS, DARK_CLASSES))
DARK_BTN_HOVER = ', '.join(f'button{t}:hover, a{t}:hover, [role="button"]{t}:hover' for t in sel(DARK_TOKENS, DARK_CLASSES))
HOVER_DARK = [f'hover:bg-{c}-{sh}' for c in ('slate', 'gray', 'zinc') for sh in ('600', '700', '800', '900', '950')]
DARK_HOVER_BTN = ', '.join(f'button.{esc(t)}:hover, a.{esc(t)}:hover' for t in HOVER_DARK)
out.append('/* buttons are never black: dark-filled buttons become light slate buttons with navy text */' + chr(10) + DARK_BTN + ' { background-color: #E2E8F0 !important; border-color: #94A3B8 !important; ' + var_block('#14213D', '#475569', 0) + ' color: #14213D; }' + chr(10) + DARK_BTN_HOVER + ', ' + DARK_HOVER_BTN + ' { background-color: #CBD5E1 !important; }')
out.append('''
/* gradient headline text becomes a solid, readable colour */
.gradient-text-blue, .gradient-text-orange {
  background: none !important;
  -webkit-background-clip: border-box !important;
  background-clip: border-box !important;
}
.gradient-text-blue { color: var(--a-blue) !important; -webkit-text-fill-color: currentColor !important; }
.gradient-text-orange { color: var(--a-amber) !important; -webkit-text-fill-color: currentColor !important; }

/* header / footer */
header { background-color: rgba(255, 255, 255, 0.85) !important; border-color: rgba(20, 33, 61, 0.1) !important; }
footer { background-color: rgba(255, 255, 255, 0.7) !important; border-color: rgba(20, 33, 61, 0.1) !important; }

/* cards */
.glass-card {
  background: rgba(255, 255, 255, 0.92) !important;
  backdrop-filter: blur(12px) !important;
  -webkit-backdrop-filter: blur(12px) !important;
  border: 1px solid rgba(20, 33, 61, 0.12) !important;
}

/* form controls: always a pale field with navy text, whatever surface they sit on */
input:not(.x), select:not(.x), textarea:not(.x) {
  background-color: #FFFFFF !important;
  border: 1px solid rgba(20, 33, 61, 0.25) !important;
  color: #14213D !important;
  -webkit-text-fill-color: #14213D !important;
  caret-color: #14213D;
}
input:not(.x)::placeholder, textarea:not(.x)::placeholder { color: #64748B !important; -webkit-text-fill-color: #64748B !important; opacity: 1; }
input:focus, select:focus, textarea:focus { border-color: #2563EB !important; outline: none !important; box-shadow: 0 0 0 3px rgba(37, 99, 235, 0.2); }
select option { color: #14213D; background: #FFFFFF; }
input:-webkit-autofill, textarea:-webkit-autofill, select:-webkit-autofill { -webkit-text-fill-color: #14213D !important; box-shadow: 0 0 0 1000px #FFFFFF inset !important; }
input[type="radio"]:not(.x), input[type="checkbox"]:not(.x) { -webkit-text-fill-color: initial !important; }
input:not(.x):disabled, select:not(.x):disabled, textarea:not(.x):disabled { background-color: #E2E8F0 !important; color: #475569 !important; -webkit-text-fill-color: #475569 !important; }

/* 3D cube decoration */
.cube-face { background: rgba(253, 224, 71, 0.15) !important; border-color: rgba(245, 158, 11, 0.4) !important; }

/* code blocks are dark panels: readable green */
pre { background-color: #0F172A !important; }
pre, pre code, pre span { color: #4ADE9C !important; -webkit-text-fill-color: #4ADE9C !important; }

/* keyboard focus must be visible */
a:focus-visible, button:focus-visible { outline: 2px solid #2563EB; outline-offset: 2px; }
''')
open(p, 'w', encoding='utf8').write(head + '\n'.join(out))
print('css bytes', len(head + '\n'.join(out)))
